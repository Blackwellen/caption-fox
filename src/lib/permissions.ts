// ── Database role aliases ────────────────────────────────────────────────────
// `workspace_members.role` stores owner | admin | manager | member | viewer |
// ugc_creator, but ROLE_PERMISSIONS was written against the product vocabulary.
// Without these aliases a real `member` resolves to zero permissions and every
// gated surface — Studio included — renders as "no access" for genuine members.
const ROLE_ALIASES: Record<string, string> = {
  member: 'creator',
  viewer: 'analyst',
  ugc_creator: 'external_creator',
}

for (const [dbRole, productRole] of Object.entries(ROLE_ALIASES)) {
  if (!ROLE_PERMISSIONS[dbRole]) ROLE_PERMISSIONS[dbRole] = [...(ROLE_PERMISSIONS[productRole] ?? [])]
}

