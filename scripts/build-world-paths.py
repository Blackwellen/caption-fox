W, H_TOP, H_BOTTOM = 360.0, 84.0, -58.0   # crop Antarctica and the far south
Y_STRETCH = 1.22                          # closer to the Miller-style proportions of the design

def project(lon, lat):
    return (lon + 180.0, (H_TOP - lat) * Y_STRETCH)

def simplify(points, tolerance=0.45):
    if len(points) < 4:
        return points
    kept = [points[0]]
    for p in points[1:-1]:
        if math.hypot(p[0] - kept[-1][0], p[1] - kept[-1][1]) >= tolerance:
            kept.append(p)
    kept.append(points[-1])
    return kept

countries = []
for g in T['objects']['countries']['geometries']:
    iso = NUM.get(str(g.get('id', '')).zfill(3), NUM.get(str(g.get('id', '')), ''))
    if iso in ('AQ', 'TF'):
        continue
    polys = g['arcs'] if g['type'] == 'MultiPolygon' else [g['arcs']] if g['type'] == 'Polygon' else []
    parts = []
    for p in polys:
        for r in p:
            pts = [project(lon, lat) for lon, lat in ring(r) if lat >= H_BOTTOM]
            pts = simplify(pts)
            if len(pts) < 3:
                continue
            # Skip rings wrapping the antimeridian badly (tiny Fiji/Russia slivers).
            xs = [q[0] for q in pts]
            if max(xs) - min(xs) > 300:
                continue
            parts.append('M' + 'L'.join(f'{x:.1f},{y:.1f}' for x, y in pts) + 'Z')
    if parts:
        countries.append((iso, g.get('properties', {}).get('name', ''), ''.join(parts)))

out = os.path.join(HERE, '..', 'src', 'components', 'strategy', 'world-paths.ts')
with open(out, 'w', encoding='utf8', newline='\n') as f:
    f.write('// GENERATED by scripts/build-world-paths.py from Natural Earth 110m (public domain). Do not edit.\n')
    f.write(f'export const WORLD_VIEWBOX = "0 0 {W:.0f} {(H_TOP - H_BOTTOM) * Y_STRETCH:.0f}"\n')
    f.write('export const WORLD_PATHS: { iso: string; name: string; d: string }[] = [\n')
    for iso, name, d in countries:
        f.write(f'  {{ iso: {json.dumps(iso)}, name: {json.dumps(name)}, d: {json.dumps(d)} }},\n')
    f.write(']\n')
print('countries', len(countries), 'bytes', os.path.getsize(out))
