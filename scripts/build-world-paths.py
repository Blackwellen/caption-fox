"""Builds src/components/strategy/world-paths.ts from Natural Earth 110m country
boundaries (world-atlas@2.0.2, public domain): one simplified SVG path per
country, tagged with its ISO 3166 alpha-2 code where known.

The Strategy audience map fills these paths from real aggregated audience
regions, so the map is data, not a picture.   Run: python scripts/build-world-paths.py
"""
import json, math, os

HERE = os.path.dirname(__file__)
T = json.load(open(os.path.join(HERE, 'data', 'countries-110m.json')))
sx, sy = T['transform']['scale']; tx, ty = T['transform']['translate']

arcs = []
for arc in T['arcs']:
    x = y = 0; pts = []
    for dx, dy in arc:
        x += dx; y += dy; pts.append((x * sx + tx, y * sy + ty))
    arcs.append(pts)

def ring(idx):
    out = []
    for i in idx:
        seg = arcs[i] if i >= 0 else list(reversed(arcs[~i]))
        out.extend(seg if not out else seg[1:])
    return out

